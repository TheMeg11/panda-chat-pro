export const dictionaries: Record<Lang, Dict> = { en, fa };

export function dirFor(lang: Lang): "ltr" | "rtl" {
  return lang === "fa" ? "rtl" : "ltr";
}

/** Resolves a dotted dictionary path ("room.saved"); falls back to the raw string. */
export function tr(t: Dict, path: string | undefined): string {
  if (!path) return "";
  let cur: unknown = t;
  for (const part of path.split(".")) {
    if (cur && typeof cur === "object" && part in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[part];
    } else {
      return path;
    }
  }
  return typeof cur === "string" ? cur : path;
}

export function errorText(t: Dict, code: string | undefined): string {
  if (!code) return "";
  return (t.errors as Record<string, string>)[code] ?? t.errors.generic;
}

export function formatNumber(n: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US").format(n);
}

export function formatDate(iso: string | Date, lang: Lang, opts: Intl.DateTimeFormatOptions = { dateStyle: "medium" }) {
  const d = typeof iso === "string" ? new Date(iso) : iso;
  return new Intl.DateTimeFormat(lang === "fa" ? "fa-IR" : "en-US", opts).format(d);
}

export function formatRelative(iso: string | Date, lang: Lang, now = Date.now()): string {
  const d = typeof iso === "string" ? new Date(iso) : iso;
  const diff = (d.getTime() - now) / 1000;
  const rtf = new Intl.RelativeTimeFormat(lang === "fa" ? "fa-IR" : "en-US", { numeric: "auto" });
  const abs = Math.abs(diff);
  if (abs < 45) return rtf.format(0, "second");
  if (abs < 3600) return rtf.format(Math.round(diff / 60), "minute");
  if (abs < 86_400) return rtf.format(Math.round(diff / 3600), "hour");
  if (abs < 86_400 * 30) return rtf.format(Math.round(diff / 86_400), "day");
  if (abs < 86_400 * 365) return rtf.format(Math.round(diff / (86_400 * 30)), "month");
  return rtf.format(Math.round(diff / (86_400 * 365)), "year");
}
